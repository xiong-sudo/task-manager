-- ============================================
-- 智能任务管理系统 · 数据库初始化脚本
-- 用法：Supabase 控制台 → SQL Editor → 新建查询 → 粘贴全部 → Run
--
-- 说明：priority 直接存中文「高 / 中 / 低」，
--       后端 server.js 与 public/app.js 已按这套值做映射。
--       本脚本使用 publishable(anon) key，因此附带匿名读写策略。
-- ============================================

create table if not exists tasks (
  id         bigint generated by default as identity primary key,
  title      text        not null,
  priority   text        not null default '中'
                         check (priority in ('高', '中', '低')),
  completed  boolean     not null default false,
  created_at timestamptz not null default now()
);

-- 列表按创建时间倒序查询，建个索引
create index if not exists tasks_created_at_idx
  on public.tasks (created_at desc);

-- ---------- 行级安全（RLS）与匿名读写策略 ----------
-- publishable / anon key 属于低权限角色，必须显式授权才能读写
alter table public.tasks enable row level security;

drop policy if exists "tasks_select_anon" on public.tasks;
create policy "tasks_select_anon" on public.tasks
  for select to anon using (true);

drop policy if exists "tasks_insert_anon" on public.tasks;
create policy "tasks_insert_anon" on public.tasks
  for insert to anon with check (true);

drop policy if exists "tasks_update_anon" on public.tasks;
create policy "tasks_update_anon" on public.tasks
  for update to anon using (true) with check (true);

drop policy if exists "tasks_delete_anon" on public.tasks;
create policy "tasks_delete_anon" on public.tasks
  for delete to anon using (true);

-- 如果你改用 secret key（sb_secret_... / service_role），它天然绕过 RLS，
-- 上面四条策略留着也不影响。

